export function viTerm(text: string): string | undefined {
  const exact = EXACT[text];
  if (exact !== undefined) return exact;
  for (const [pattern, render] of PATTERNS) {
    const match = pattern.exec(text);
    if (match) return render(match);
  }
  return undefined;
}
